"use strict";
/* Offline snapshot shim for the Crophecy Pages mirror. Runs first on every exported page.
   - fetch("/harvest/api/...") is answered from snap/api.json (responses recorded from the live server at export time);
     writes (join, bet, chat, theory) get a 503 that says this is an offline snapshot.
   - root-absolute links ("/app/replay", "/market/x", "/harvest/api/verify") are mapped to the snapshot page that holds
     them, or to the live site when the snapshot has no copy.
   - history.replaceState on the single-page app keeps the URL inside the snapshot (hash routes).
   Generated by export_static_snapshot.py; nothing leaves the browser. */
(() => {
  const script = document.currentScript;
  const ROOT = new URL(".", script.src).href; // this file sits at the site root
  const LIVE = script.getAttribute("data-live") || "https://crophecy.bid";
  const API = "/harvest/api";
  const realFetch = window.fetch.bind(window);
  const LOCAL_APP = new Set(["leaderboard", "replay", "impact"]);
  let store = null;
  const load = () => (store || (store = realFetch(ROOT + "snap/api.json").then((r) => r.json()).catch(() => ({}))));
  const reply = (status, body) => new Response(JSON.stringify(body), { status, headers: { "Content-Type": "application/json" } });
  const miss = [];
  window.__snapshotMisses = miss;

  window.fetch = async function (input, init) {
    const req = typeof input === "string" || input instanceof URL ? null : input;
    const url = new URL(req ? req.url : String(input), location.href);
    const method = ((init && init.method) || (req && req.method) || "GET").toUpperCase();
    const path = url.pathname;
    if (url.origin === location.origin && path.startsWith(API + "/")) {
      const key = path.slice(API.length) + url.search;
      const snap = await load();
      if (method === "GET") {
        let hit = snap["GET " + key];
        if (!hit && /^\/site$/.test(path) && url.searchParams.has("since")) hit = snap["GET /site?since=*"];
        if (!hit) hit = snap["GET " + path.slice(API.length)];
        if (hit) return reply(hit.status, hit.body);
        miss.push(key);
        console.warn("snapshot: no copy of", key);
        return reply(404, { error: "This view is not in the offline snapshot." });
      }
      if (method === "POST" && path === API + "/verify") {
        let body = {};
        try { body = JSON.parse((init && init.body) || (req ? await req.clone().text() : "{}")) || {}; } catch (_) { /* not JSON */ }
        const hit = snap[body.tamper ? "POST /verify tamper" : "GET /verify"];
        if (hit) return reply(hit.status, hit.body);
      }
      return reply(503, { error: "This is an offline snapshot of crophecy.bid. Joining, betting and chat work on the live site." });
    }
    if (method === "HEAD" && url.origin === location.origin && /^\/harvest\/static\/croppy/.test(path)) {
      return new Response(null, { status: 404 }); // optional widgets (the chat helper) stay off in the snapshot
    }
    return realFetch(input, init);
  };

  // ------------------------------------------------------------ assets the page scripts add (images, scripts, stylesheets)
  const ASSET = /^\/(frontend|harvest\/static|waitlist)\//;
  const fixAsset = (v) => (typeof v === "string" && ASSET.test(v) ? ROOT + v.slice(1) : v);
  const setAttr = Element.prototype.setAttribute;
  Element.prototype.setAttribute = function (name, value) {
    const n = String(name).toLowerCase();
    return setAttr.call(this, name, n === "src" || n === "poster" || (n === "href" && this.tagName === "LINK") ? fixAsset(value) : value);
  };
  for (const [proto, prop] of [[HTMLImageElement, "src"], [HTMLScriptElement, "src"], [HTMLSourceElement, "src"], [HTMLMediaElement, "src"], [HTMLMediaElement, "poster"]]) {
    const d = Object.getOwnPropertyDescriptor(proto.prototype, prop);
    if (d && d.set) Object.defineProperty(proto.prototype, prop, { ...d, set(v) { d.set.call(this, fixAsset(v)); } });
  }

  // ------------------------------------------------------------ links
  function mapPath(href) {
    const u = new URL(href, location.href);
    const p = u.pathname.replace(/\/+$/, "") || "/";
    const tail = u.search + u.hash;
    const spa = (hash) => ROOT + "#" + hash;
    if (p === "/" || p === "/home") return p === "/" ? ROOT + tail : spa("home");
    if (p === "/live" || p === "/markets" || p === "/theory" || p === "/farmer") return spa(p.slice(1));
    if (p.startsWith("/market/")) return spa("m-" + p.slice(8));
    if (p === "/leaderboard") return ROOT + "app/leaderboard.html" + tail;
    if (p.startsWith("/app/market/")) return spa("m-" + p.slice(12));
    if (["markets", "live", "theory", "farmer"].some((v) => p === "/app/" + v)) return spa(p.slice(5));
    const m = /^\/app\/(\w+)$/.exec(p);
    if (m && LOCAL_APP.has(m[1])) return ROOT + "app/" + m[1] + ".html" + tail;
    if (p === "/app") return ROOT + tail;
    return LIVE + u.pathname + tail;
  }
  const rewrite = (a) => {
    const h = a.getAttribute("href");
    if (h && h.startsWith("/") && !h.startsWith("//")) {
      a.setAttribute("data-live-href", h);
      a.setAttribute("href", mapPath(h));
      if (a.getAttribute("href").startsWith(LIVE) && !a.target) { a.target = "_blank"; a.rel = "noopener"; }
    }
  };
  const sweep = (root) => { if (root.nodeType === 1) { if (root.matches("a[href^='/']")) rewrite(root); root.querySelectorAll("a[href^='/']").forEach(rewrite); } };
  document.addEventListener("click", (e) => {
    const a = e.target.closest && e.target.closest("a[href^='/']");
    if (a && !a.getAttribute("href").startsWith("//")) rewrite(a);
  }, true);
  const start = () => {
    sweep(document.documentElement);
    new MutationObserver((muts) => { for (const m of muts) m.addedNodes.forEach(sweep); }).observe(document.documentElement, { childList: true, subtree: true });
  };
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", start); else start();

  // ------------------------------------------------------------ history: stay inside the snapshot
  for (const name of ["replaceState", "pushState"]) {
    const orig = history[name].bind(history);
    history[name] = (state, title, url) => {
      if (typeof url === "string" && url.startsWith("/")) {
        const target = new URL(mapPath(url), location.href);
        if (target.href.startsWith(ROOT) && target.hash) { const here = new URL(location.href); here.hash = target.hash; return orig(state, title, here.href); }
        if (target.href === ROOT || target.href === ROOT + "index.html") { const here = new URL(location.href); here.hash = ""; return orig(state, title, here.href); }
        return undefined;
      }
      return orig(state, title, url);
    };
  }
})();
