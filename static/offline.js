"use strict";
/* Harvest offline demo: answers the pages' /harvest/api/* calls in the browser.
   The book is rebuilt from the frozen ledger snapshot (api/seed.json), the house world models keep trading on
   their sealed forecasts with the server's decide() rule, and a viewer's own join, bets and time-machine
   answers live in localStorage. Nothing leaves the browser. Generated by export_static_demo.py. */
(() => {
  const ROOT = new URL("..", document.currentScript.src).href;
  const realFetch = window.fetch.bind(window);
  const FEE_RATE = 0.02, START = 1000, MAX_BET_SHARE = 0.2, EPS = 1e-9, SPEND_MIN = 1, SPEND_MAX = 500, TICK_MS = 3000;
  const KEY = "harvest-offline-v1";
  const NICK_EXTRA = new Set(" _-.!+'");

  // ---------------------------------------------------------------- LMSR (agent/harvest/lmsr.py)
  function cost(qy, qn, b) { const m = Math.max(qy, qn) / b; return b * (m + Math.log(Math.exp(qy / b - m) + Math.exp(qn / b - m))); }
  function priceYes(qy, qn, b) { return 1 / (1 + Math.exp((qn - qy) / b)); }
  function sharesForSpend(qy, qn, b, side, spend) {
    const [mine, other] = side === "YES" ? [qy, qn] : [qn, qy];
    const target = (cost(qy, qn, b) + spend) / b;
    const m = Math.max(target, other / b);
    return b * (m + Math.log(Math.exp(target - m) - Math.exp(other / b - m))) - mine;
  }
  const clamp = (x, lo, hi) => Math.min(Math.max(x, lo), hi);
  class ApiError extends Error { constructor(msg, status) { super(msg); this.status = status; } }

  // ---------------------------------------------------------------- book (agent/harvest/market.py)
  class Book {
    constructor() {
      this.markets = new Map(); this.meta = new Map(); this.forecastsByQ = new Map();
      this.accounts = new Map(); this.holdings = new Map(); this.spent = new Map();
      this.trades = []; this.fund = 0; this.traders = new Map(); this.tokens = new Map(); this.forecasts = new Map();
    }
    open(qid, prior, b) {
      const p = clamp(prior, 0.01, 0.99);
      const m = { qid, b, q_yes: b * Math.log(p / (1 - p)), q_no: 0, volume: 0, fees: 0, status: "open", outcome: null, history: [] };
      m.history.push([this.trades.length, priceYes(m.q_yes, m.q_no, b)]);
      this.markets.set(qid, m);
    }
    price(qid) { const m = this.markets.get(qid); return priceYes(m.q_yes, m.q_no, m.b); }
    balance(t) { if (!this.accounts.has(t)) this.accounts.set(t, START); return this.accounts.get(t); }
    buy(trader, qid, side, spend, at) {
      if (side !== "YES" && side !== "NO") throw new ApiError("side must be YES or NO", 422);
      if (!Number.isFinite(spend) || spend <= 0) throw new ApiError("spend must be positive", 422);
      const m = this.markets.get(qid);
      if (!m) throw new ApiError(`unknown market '${qid}'`, 404);
      if (m.status !== "open") throw new ApiError(`market '${qid}' is closed`, 422);
      const bal = this.balance(trader);
      if (spend > bal + EPS) throw new ApiError(`insufficient credits: ${bal.toFixed(2)} available, ${spend.toFixed(2)} asked`, 422);
      const fee = FEE_RATE * spend, before = this.price(qid);
      const shares = sharesForSpend(m.q_yes, m.q_no, m.b, side, spend - fee);
      if (side === "YES") m.q_yes += shares; else m.q_no += shares;
      const after = this.price(qid);
      this.accounts.set(trader, bal - spend);
      const k = `${trader}|${qid}`;
      const hold = this.holdings.get(k) || { YES: 0, NO: 0 };
      hold[side] += shares;
      this.holdings.set(k, hold);
      this.spent.set(k, (this.spent.get(k) || 0) + spend);
      m.volume += spend; m.fees += fee; this.fund += fee;
      const trade = { seq: this.trades.length + 1, trader, qid, side, spend, fee, shares, price_before: before, price_after: after, at: at || new Date().toISOString(), cutoff: null };
      this.trades.push(trade);
      m.history.push([trade.seq, after]);
      return trade;
    }
    positions(trader) {
      const out = [];
      for (const [k, hold] of this.holdings) {
        const i = k.lastIndexOf("|"), t = k.slice(0, i), qid = k.slice(i + 1);
        if (t !== trader) continue;
        const p = this.price(qid), spent = this.spent.get(k) || 0, value = hold.YES * p + hold.NO * (1 - p);
        out.push({ qid, yes: hold.YES, no: hold.NO, spent, value, pnl: value - spent, p_yes: p, status: "open", outcome: null });
      }
      return out;
    }
    equity(t) { return this.balance(t) + this.positions(t).reduce((a, p) => a + p.value, 0); }
    view(qid, full) {
      const m = this.markets.get(qid), q = this.meta.get(qid) || {};
      const v = { ...q, qid, p_yes: this.price(qid), b: m.b, volume: m.volume, fees: m.fees, status: m.status, outcome: m.outcome,
        history: (full ? m.history : m.history.slice(-120)).map((h) => [...h]), agent_forecasts: this.forecastsByQ.get(qid) || [] };
      if (full) v.trades = this.trades.filter((t) => t.qid === qid).slice(-200);
      return v;
    }
  }

  // ---------------------------------------------------------------- per-viewer state
  let local = { actions: [] };
  const loadLocal = () => { try { return JSON.parse(localStorage.getItem(KEY) || "null") || { actions: [] }; } catch (_) { return local; } };
  const saveLocal = (v) => { try { localStorage.setItem(KEY, JSON.stringify(v)); } catch (_) { /* storage blocked: this tab only */ } };
  local = loadLocal();

  // ---------------------------------------------------------------- boot
  let seed = null, book = null, applied = 0;
  const personaById = new Map();
  const ready = (async () => {
    const r = await realFetch(new URL("api/seed.json", ROOT));
    seed = await r.json();
    for (const p of seed.personas) personaById.set(p.id, p);
    book = new Book();
    for (const m of seed.markets) {
      book.meta.set(m.qid, m.meta);
      book.forecastsByQ.set(m.qid, m.agent_forecasts);
      book.open(m.qid, m.prior, m.b);
    }
    // shift the frozen trades so the latest one is "now": the feed reads as a replay, not as stale hours
    const last = Date.parse(seed.entries[seed.entries.length - 1].at), shift = Date.now() - last;
    const at = (iso) => new Date(Date.parse(iso) + shift).toISOString();
    for (const e of seed.entries) applyEntry(e.kind, e.trader, e.payload, at(e.at));
    applyLocal();
    setInterval(houseStep, TICK_MS);
    window.addEventListener("storage", (ev) => { if (ev.key === KEY) { local = loadLocal(); applyLocal(); } });
  })();

  function applyEntry(kind, trader, p, at) {
    if (kind === "join") {
      if (!book.traders.has(trader)) book.traders.set(trader, { kind: "human", nickname: p.nickname });
      if (p.token) book.tokens.set(p.token, trader);
      book.balance(trader);
    } else if (kind === "forecast") {
      book.forecasts.set(trader, { ...p, at });
    } else if (kind === "bet") {
      try { return book.buy(trader, p.qid, p.side, p.spend, at); } catch (_) { return null; }
    }
    return null;
  }
  function applyLocal() {
    for (; applied < local.actions.length; applied++) {
      const a = local.actions[applied];
      applyEntry(a.kind, a.trader, a, a.at);
    }
  }
  function record(action) {
    local = loadLocal();
    applyLocal();
    local.actions.push(action);
    saveLocal(local);
    applyLocal();
  }

  // ---------------------------------------------------------------- house world models keep trading (market.decide)
  function decide(persona, pYes, price, bankroll) {
    const gap = pYes - price, edge = Number(persona.edge ?? 0.03);
    if (Math.abs(gap) <= edge || bankroll <= 0) return null;
    const spend = Math.round(Math.min(Number(persona.risk ?? 0.25) * bankroll * Math.abs(gap), MAX_BET_SHARE * bankroll) * 100) / 100;
    return spend < 0.01 ? null : { side: gap > 0 ? "YES" : "NO", spend };
  }
  function houseStep() {
    const options = [];
    for (const [qid, fs] of book.forecastsByQ) if (book.markets.has(qid)) for (const f of fs) options.push([qid, f]);
    for (let i = options.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [options[i], options[j]] = [options[j], options[i]]; }
    for (const [qid, f] of options.slice(0, 24)) {
      const persona = personaById.get(f.persona_id);
      if (!persona) continue;
      const trader = `agent:${persona.id}`;
      const intent = decide(persona, f.p_yes, book.price(qid), book.balance(trader));
      if (!intent) continue;
      book.buy(trader, qid, intent.side, intent.spend);
      return;
    }
  }

  // ---------------------------------------------------------------- views (agent/routes/harvest.py)
  function humanRows() {
    const out = [];
    for (const [id, info] of book.traders) {
      if (info.kind !== "human") continue;
      const fc = book.forecasts.get(id) || {};
      out.push({ user_id: id, nickname: info.nickname, brier: fc.brier ?? null, n: fc.n || 0, rank_vs_world_models: fc.rank_vs_world_models ?? null,
        balance: book.balance(id), pnl: book.equity(id) - START, trades: book.trades.filter((t) => t.trader === id).length });
    }
    return out.sort((a, b) => (a.brier == null) - (b.brier == null) || (a.brier || 0) - (b.brier || 0) || b.pnl - a.pnl);
  }
  function leaderboard() {
    const lb = seed.leaderboard;
    const wm = lb.world_models.map((m) => (m.origin === "house" ? { ...m, pnl_live: book.equity(`agent:${m.persona_id}`) - START } : { ...m }));
    return { world_models: wm, baselines: lb.baselines, humans: humanRows(), insight: lb.insight };
  }
  function fund() {
    const groups = new Map();
    for (const [qid, m] of book.markets) {
      if (m.status !== "open") continue;
      const q = book.meta.get(qid) || {}, p = book.price(qid);
      const k = `${q.region || "Europe"}|${q.crop || "mixed"}`;
      if (!groups.has(k)) groups.set(k, []);
      groups.get(k).push([qid, (q.adverse_if || "yes") === "yes" ? p : 1 - p]);
    }
    const risks = [...groups].map(([k, v]) => [k, v.reduce((a, x) => a + x[1], 0) / v.length]).sort((a, b) => b[1] - a[1]);
    const total = risks.reduce((a, r) => a + r[1], 0);
    const allocations = risks.map(([k, risk]) => {
      const [region, crop] = k.split("|"), share = total > 0 ? risk / total : 0;
      return { region, crop, risk, share, amount: share * book.fund, questions: groups.get(k).map((x) => x[0]) };
    });
    return { treasury: book.fund, fee_rate: FEE_RATE, allocations, memo: seed.fund.memo, receipt: seed.fund.receipt, earmark: seed.fund.earmark };
  }
  function state(since) {
    const lb = leaderboard();
    const recent = since != null ? book.trades.filter((t) => t.seq > since).slice(-200) : book.trades.slice(-50);
    return {
      personas: seed.personas.map(({ id, name, color, world_model, beliefs, heuristic }) => ({ id, name, color, world_model, beliefs, heuristic })),
      markets: [...book.markets.keys()].map((q) => book.view(q)), recent_trades: recent,
      seq: book.trades.length ? book.trades[book.trades.length - 1].seq : 0, leaderboard: lb, fund: fund(),
      users: [...book.traders.values()].filter((t) => t.kind === "human").length, agents: 0,
      ledger_head: seed.ledger_head, insight: lb.insight, has_replay: true, offline: true,
    };
  }

  // ---------------------------------------------------------------- writes
  async function sha256hex(text) {
    if (window.crypto && crypto.subtle) {
      const buf = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(text));
      return [...new Uint8Array(buf)].map((b) => b.toString(16).padStart(2, "0")).join("");
    }
    let h = 2166136261; for (const ch of text) { h ^= ch.codePointAt(0); h = Math.imul(h, 16777619); }
    return (h >>> 0).toString(16).padStart(8, "0").repeat(8);
  }
  function nickname(raw) {
    if (typeof raw !== "string") throw new ApiError("nickname must be text", 422);
    const kept = [...raw.normalize("NFKC")].filter((ch) => /[\p{L}\p{N}]/u.test(ch) || NICK_EXTRA.has(ch)).join("");
    const nick = kept.split(/\s+/).filter(Boolean).join(" ").slice(0, 24).trim();
    if (!nick) throw new ApiError("pick a nickname (letters and digits, up to 24 characters)", 422);
    return nick;
  }
  const traderFor = (token) => (token ? book.tokens.get(String(token)) : undefined);
  const num = (x) => { const v = Number(x); return x === null || x === "" || !Number.isFinite(v) ? null : v; };

  async function join(body) {
    const nick = nickname(body.nickname);
    const user_id = `user:${(await sha256hex(`challenge-nick:v1:${nick.toLowerCase()}`)).slice(0, 12)}`;
    const token = Array.from(crypto.getRandomValues(new Uint8Array(18)), (b) => b.toString(16).padStart(2, "0")).join("");
    const action = { kind: "join", trader: user_id, nickname: nick, token, at: new Date().toISOString() };
    record(action);
    return { user_id, nickname: nick, token, credits: book.balance(user_id), users: [...book.traders.values()].filter((t) => t.kind === "human").length };
  }
  function bet(body) {
    const trader = traderFor(body.token);
    if (!trader) throw new ApiError("unknown token; join or register first", 401);
    const side = String(body.side || "").trim().toUpperCase();
    if (side !== "YES" && side !== "NO") throw new ApiError("side must be YES or NO", 422);
    const spend = num(body.spend);
    if (spend == null) throw new ApiError("spend must be a number", 422);
    const s = Math.round(clamp(spend, SPEND_MIN, SPEND_MAX) * 100) / 100;
    const at = new Date().toISOString();
    local = loadLocal();
    applyLocal();
    const trade = book.buy(trader, String(body.qid || ""), side, s, at);
    local.actions.push({ kind: "bet", trader, qid: trade.qid, side, spend: s, at });
    saveLocal(local);
    applied = local.actions.length;
    return { trade, market: book.view(trade.qid), balance: book.balance(trader) };
  }
  function forecast(body) {
    const trader = traderFor(body.token);
    if (!trader) throw new ApiError("unknown token; join first", 401);
    if (!Array.isArray(body.answers) || !body.answers.length) throw new ApiError("answers must be a non-empty list of {qid, p_yes}", 422);
    const answers = [];
    for (const a of body.answers.slice(0, 64)) {
      const p = a && typeof a === "object" ? num(a.p_yes) : null;
      if (p == null || typeof a.qid !== "string") throw new ApiError("each answer needs a qid and a numeric p_yes", 422);
      answers.push([a.qid, clamp(p, 0.01, 0.99)]);
    }
    const byQ = new Map(seed.holdout.map((h) => [h.qid, h]));
    const scored = answers.filter(([q]) => byQ.has(q) && byQ.get(q).outcome != null);
    if (!scored.length) throw new ApiError("no answered question is a resolved holdout question", 422);
    const brier = scored.reduce((a, [q, p]) => a + (p - byQ.get(q).outcome) ** 2, 0) / scored.length;
    const models = [];
    for (const persona of seed.personas) {
      const pairs = scored.map(([q]) => [byQ.get(q).forecasts[persona.id], byQ.get(q).outcome]).filter(([p]) => p != null);
      if (pairs.length) models.push({ persona_id: persona.id, name: persona.name, brier: pairs.reduce((a, [p, o]) => a + (p - o) ** 2, 0) / pairs.length });
    }
    models.sort((a, b) => a.brier - b.brier);
    const rank = 1 + models.filter((m) => m.brier < brier).length;
    const reveal = scored.map(([q]) => byQ.get(q).resolution);
    const payload = { answers: answers.map(([qid, p_yes]) => ({ qid, p_yes })), brier, n: scored.length, rank_vs_world_models: rank, of: models.length + 1 };
    record({ kind: "forecast", trader, ...payload, at: new Date().toISOString() });
    return { brier, n: scored.length, rank_vs_world_models: rank, of: models.length + 1, world_models: models, reveal };
  }
  function me(token) {
    const trader = traderFor(token);
    if (!trader) throw new ApiError("unknown token; join first", 401);
    const info = book.traders.get(trader) || {};
    return { user_id: trader, nickname: info.nickname, balance: book.balance(trader), equity: book.equity(trader), pnl: book.equity(trader) - START,
      positions: book.positions(trader), forecast: book.forecasts.get(trader) || null };
  }

  // ---------------------------------------------------------------- routing
  const file = (name) => realFetch(new URL(`api/${name}`, ROOT));
  async function route(url, method, body) {
    const path = url.pathname.replace(/^.*\/harvest\/api\//, "");
    if (method === "GET") {
      if (path === "story" || path === "geo" || path === "ledger" || path === "holdout" || path === "agents") return file(`${path}.json`);
      if (path === "verify") return file("verify.json");
      if (path === "playurl") return json({ url: new URL("play.html", ROOT).href });
      await ready;
      if (path === "state") { const s = url.searchParams.get("since"); return json(state(s == null ? null : Number(s))); }
      if (path === "markets") return json({ markets: [...book.markets.keys()].map((q) => book.view(q)) });
      if (path.startsWith("markets/")) {
        const qid = decodeURIComponent(path.slice(8));
        return book.markets.has(qid) ? json(book.view(qid, true)) : json({ error: `unknown market '${qid}'` }, 404);
      }
      if (path === "leaderboard") return json(leaderboard());
      if (path === "fund") return json(fund());
      if (path === "me") return json(me(url.searchParams.get("token")));
      if (path === "prices") return json({ error: "not in the offline demo", series: {} });
      return json({ error: "not available in the offline demo" }, 404);
    }
    if (path === "verify") return file(body && body.tamper ? "verify-tamper.json" : "verify.json");
    await ready;
    if (path === "join") return json(await join(body));
    if (path === "bet" || path === "agents/bet") return json(bet(body));
    if (path === "forecast") return json(forecast(body));
    return json({ error: "the agent API runs only on the live server" }, 404);
  }
  function json(data, status = 200) {
    return new Response(JSON.stringify(data), { status, headers: { "Content-Type": "application/json" } });
  }

  window.fetch = async (input, init = {}) => {
    const raw = typeof input === "string" ? input : input instanceof URL ? input.href : input.url;
    const url = new URL(raw, location.href);
    if (!url.pathname.includes("/harvest/api/")) return realFetch(input, init);
    const method = (init.method || "GET").toUpperCase();
    let body = null;
    if (init.body) { try { body = JSON.parse(init.body); } catch (_) { return json({ error: "Body must be JSON." }, 400); } }
    try {
      return await route(url, method, body || {});
    } catch (err) {
      return json({ error: err.message }, err.status || 500);
    }
  };
  window.HarvestOffline = { ready, book: () => book };
})();
